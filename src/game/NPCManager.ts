const PRAISE = [
  'В этом холсте столько света, что я повесил(а) его напротив окна — теперь в комнате два солнца.',
  'Мазки живые! Я три часа смотрел(а) и забыл(а), что собирался(ась) обедать.',
  'Показал(а) коту — кот одобрил. А мой кот не одобрял ничего со времён переезда.',
  'Цвет замешан так, будто вы подсмотрели его у самого заката.',
  'Повесил(а) в гостиной — гости теперь приходят «просто посмотреть» и забывают уйти.',
  'В этой работе чувствуется рука мастера и сердце человека, который любит своё дело.',
  'Я коллекционирую искусство 20 лет. Такой фактуры не видел(а) никогда. Браво!',
  'Картина пахнет краской и счастьем. Не спрашивайте, как я это определил(а) через экран.',
];

export class NPCManager {
  private npcs: NPC[] = [];
  private byIdMap = new Map<number, NPC>();

  constructor() {
    let id = 1;
    const usedNames = new Set<string>();
    while (this.npcs.length < 128) {
      const name = `${pick(FIRST)} ${pick(LAST)}`;
      if (usedNames.has(name)) continue;
      usedNames.add(name);
      const tier = Math.min(6, 1 + Math.floor(this.npcs.length / 22));
      const budget = Math.round(priceCap(tier) * rand(0.55, 1.25));
      const login = `${name.split(' ')[0].toLowerCase().replace(/[^а-яa-z]/g, '')}${id}`;
      const npc: NPC = {
        id, name,
        trait: pick(TRAITS),
        style: pick(STYLES),
        budget, tier,
        email: `${login}@${pick(DOMAINS)}`,
      };
      this.npcs.push(npc);
      this.byIdMap.set(id, npc);
      id++;
    }
  }

  byId(id: number): NPC | undefined { return this.byIdMap.get(id); }

  buyerFor(level: number): NPC {
    const maxTier = Math.min(6, level + 1);
    const pool = this.npcs.filter(n => n.tier <= maxTier);
    return pick(pool);
  }

  commission(level: number): { brief: string; style: string; reward: number; size: PaperKind } {
    const size: PaperKind = level >= 3 && Math.random() < 0.5 ? (Math.random() < 0.5 ? 'canvas' : 'a3') : (Math.random() < 0.6 ? 'a4' : 'a3');
    const base = priceCap(level);
    return {
      brief: pick(SUBJECTS),
      style: pick(STYLES),
      reward: Math.round(base * rand(0.8, 1.3)),
      size,
    };
  }

  sarcasticOverprice(price: number, cap: number): string {
    let s = pick(SARCASM);
    if (s.includes('%CAP%')) s = s.replace('%CAP%', fmtMoney(cap));
    if (Math.random() < 0.5) s += `\n\nP.S. Ваша цена (${fmtMoney(price)}) при текущем уровне репутации превышает предел в ${Math.round(price / Math.max(1, cap))} раз(а).`;
    return s;
  }

  praise(p: PaintingMeta): string {
    let s = pick(PRAISE);
    if (p.quality >= 75) s += '\n\nКачество — музейное, не иначе.';
    else if (p.quality >= 55) s += '\n\nОчень достойная работа.';
    else s += '\n\nЧувствуется, что автор ещё растёт — и это прекрасно.';
    return s;
  }
}
